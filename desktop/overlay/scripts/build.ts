/**
 * Bundles the overlay to `dist/overlay.js` and embeds it in the Swift app as
 * `Sources/SpiderDesktop/Generated/OverlayScript.swift`, so the binary needs
 * no resource lookup at runtime.
 */

import {mkdir, readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {build} from 'esbuild';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const outfile = path.join(root, 'dist', 'overlay.js');
const generatedDir = path.resolve(root, '..', 'SpiderDesktop', 'Sources', 'SpiderDesktop', 'Generated');
const generatedFile = path.join(generatedDir, 'OverlayScript.swift');

await build({
  entryPoints: [path.join(root, 'src', 'main.ts')],
  bundle: true,
  format: 'iife',
  target: ['safari17'],
  outfile,
  legalComments: 'none',
  logLevel: 'info',
});

const js = await readFile(outfile, 'utf8');
if (js.includes('"""##')) {
  throw new Error('overlay.js contains the raw string delimiter """## and cannot be embedded');
}
const swift =
  '// Generated by desktop/overlay/scripts/build.ts from the overlay sources. Do not edit.\n\n' +
  'enum OverlayScript {\n' +
  '  static let source = ##"""\n' +
  `${js}\n` +
  '"""##\n' +
  '}\n';
await mkdir(generatedDir, {recursive: true});
await writeFile(generatedFile, swift);
console.log(`wrote ${path.relative(root, generatedFile)} (${(js.length / 1024).toFixed(1)} KB)`);
