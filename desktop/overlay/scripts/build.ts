/**
 * Bundles the overlay to `dist/overlay.js` and the DOM-free text extractor to
 * `dist/text-core.js`, and embeds each in the Swift app as
 * `Sources/SpiderDesktop/Generated/<Name>.swift`, so the binary needs no
 * resource lookup at runtime.
 */

import {mkdir, readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {build} from 'esbuild';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const generatedDir = path.resolve(root, '..', 'SpiderDesktop', 'Sources', 'SpiderDesktop', 'Generated');

interface Bundle {
  readonly entry: string;
  readonly outName: string;
  readonly swiftType: string;
  /** Substrings that must not appear in the output. */
  readonly forbidden: readonly string[];
}

const BUNDLES: readonly Bundle[] = [
  {entry: 'main.ts', outName: 'overlay.js', swiftType: 'OverlayScript', forbidden: []},
  // JavaScriptCore has no DOM, so any `document.` here would fail only at runtime.
  {entry: 'text-entry.ts', outName: 'text-core.js', swiftType: 'TextCoreScript', forbidden: ['document.']},
];

await mkdir(generatedDir, {recursive: true});
for (const bundle of BUNDLES) {
  const outfile = path.join(root, 'dist', bundle.outName);
  await build({
    entryPoints: [path.join(root, 'src', bundle.entry)],
    bundle: true,
    format: 'iife',
    target: ['safari17'],
    outfile,
    legalComments: 'none',
    logLevel: 'info',
  });

  const js = await readFile(outfile, 'utf8');
  if (js.includes('"""##')) {
    throw new Error(`${bundle.outName} contains the raw string delimiter """## and cannot be embedded`);
  }
  for (const text of bundle.forbidden) {
    if (js.includes(text)) {
      throw new Error(`${bundle.outName} must not contain "${text}"`);
    }
  }
  const swift =
    '// Generated by desktop/overlay/scripts/build.ts from the overlay sources. Do not edit.\n\n' +
    `enum ${bundle.swiftType} {\n` +
    '  static let source = ##"""\n' +
    `${js}\n` +
    '"""##\n' +
    '}\n';
  const generatedFile = path.join(generatedDir, `${bundle.swiftType}.swift`);
  await writeFile(generatedFile, swift);
  console.log(`wrote ${path.relative(root, generatedFile)} (${(js.length / 1024).toFixed(1)} KB)`);
}
